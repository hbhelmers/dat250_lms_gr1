CREATE TABLE course_modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    position INTEGER NOT NULL CHECK (position >= 0),
    CONSTRAINT module_position_unique UNIQUE (course_id, position) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE content_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL REFERENCES course_modules(id) ON DELETE CASCADE,
    type VARCHAR(32) NOT NULL CHECK (type IN ('PAGE')),
    title VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    position INTEGER NOT NULL CHECK (position >= 0),
    published BOOLEAN NOT NULL DEFAULT FALSE,
    visible_from TIMESTAMP WITH TIME ZONE,
    visible_until TIMESTAMP WITH TIME ZONE,
    CONSTRAINT content_visibility_window CHECK (visible_from IS NULL OR visible_until IS NULL OR visible_from < visible_until),
    CONSTRAINT content_position_unique UNIQUE (module_id, position) DEFERRABLE INITIALLY DEFERRED
);
