ALTER TABLE content_items DROP CONSTRAINT content_items_type_check;
ALTER TABLE content_items ADD CONSTRAINT content_items_type_check CHECK (type IN ('PAGE', 'QUIZ', 'ASSIGNMENT'));

CREATE TABLE assignments (
    content_item_id BIGINT PRIMARY KEY REFERENCES content_items(id) ON DELETE CASCADE,
    deadline TIMESTAMP WITH TIME ZONE,
    accept_late BOOLEAN NOT NULL
);

CREATE TABLE assignment_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(content_item_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    version INTEGER NOT NULL CHECK (version > 0),
    submission_id UUID NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    late BOOLEAN NOT NULL,
    object_key VARCHAR(100) NOT NULL UNIQUE,
    filename VARCHAR(255) NOT NULL,
    media_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 10485760),
    sha256 VARCHAR(64) NOT NULL,
    grade VARCHAR(16) CHECK (grade IN ('A','B','C','D','E','F','PASSED','FAILED')),
    feedback TEXT NOT NULL DEFAULT '',
    grade_published BOOLEAN NOT NULL DEFAULT FALSE,
    graded_at TIMESTAMP WITH TIME ZONE,
    CHECK (NOT grade_published OR (grade IS NOT NULL AND graded_at IS NOT NULL)),
    UNIQUE (assignment_id, user_id, version),
    UNIQUE (assignment_id, user_id, submission_id)
);
CREATE INDEX assignment_submissions_assignment_idx ON assignment_submissions(assignment_id, submitted_at DESC);

-- Cascades also enqueue removal of S3 objects. Cleanup retries if storage is offline.
CREATE TABLE pending_object_deletions (
    object_key VARCHAR(100) PRIMARY KEY,
    queued_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION queue_submission_object_deletion() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO pending_object_deletions(object_key) VALUES (OLD.object_key) ON CONFLICT DO NOTHING;
    RETURN OLD;
END;
$$;
CREATE TRIGGER submission_object_cleanup AFTER DELETE ON assignment_submissions
    FOR EACH ROW EXECUTE FUNCTION queue_submission_object_deletion();
