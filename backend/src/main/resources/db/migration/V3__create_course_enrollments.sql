CREATE TABLE course_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(16) NOT NULL CHECK (role IN ('TEACHER', 'STUDENT')),
    CONSTRAINT course_enrollment_unique UNIQUE (course_id, user_id)
);

CREATE INDEX course_enrollments_user_idx ON course_enrollments(user_id);

-- Only courses that predate memberships need an explicitly configured teacher.
