ALTER TABLE content_items DROP CONSTRAINT content_items_type_check;
ALTER TABLE content_items ADD CONSTRAINT content_items_type_check CHECK (type IN ('PAGE', 'QUIZ'));

CREATE TABLE quizzes (
    content_item_id BIGINT PRIMARY KEY REFERENCES content_items(id) ON DELETE CASCADE,
    max_attempts INTEGER NOT NULL CHECK (max_attempts BETWEEN 1 AND 20),
    deadline TIMESTAMP WITH TIME ZONE,
    results_visible BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(content_item_id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 0),
    prompt VARCHAR(2000) NOT NULL,
    hint VARCHAR(2000) NOT NULL DEFAULT '',
    correct_option INTEGER NOT NULL CHECK (correct_option BETWEEN 0 AND 7),
    CONSTRAINT quiz_question_position_unique UNIQUE (quiz_id, position) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE quiz_options (
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position BETWEEN 0 AND 7),
    label VARCHAR(1000) NOT NULL,
    PRIMARY KEY (question_id, position)
);
CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(content_item_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    submission_id UUID NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    score INTEGER NOT NULL,
    total INTEGER NOT NULL,
    CHECK (total > 0 AND score BETWEEN 0 AND total),
    UNIQUE (quiz_id, user_id, attempt_number),
    UNIQUE (quiz_id, user_id, submission_id)
);
CREATE TABLE quiz_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    selected_option INTEGER NOT NULL CHECK (selected_option BETWEEN 0 AND 7),
    correct BOOLEAN NOT NULL,
    UNIQUE (attempt_id, question_id)
);
